public class ComparisonOperators {

    public static void main(String[] args) {

        var a = 5;
        var b = 3;

        // Comparison operators

        System.out.println(a == b);
        System.out.println(a != b);
        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a >= b);
        System.out.println(a <= b);

    }
}