public class Conditionals {

    public static void main(String[] args) {

        // switch
        var day = 1;

        switch (day) {
            case 1:
                System.out.println("Lunes");
                break;
            case 2:
                System.out.println("Martes");
                break;
            case 3:
                System.out.println("Miércoles");
                break;
        }
    }
}